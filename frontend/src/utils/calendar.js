/**
 * Calendar export utilities compliant with RFC 5545 (iCalendar) and Google Calendar web link.
 */

/**
 * Escapes plain text for RFC 5545 compliance (escaping backslashes, semicolons, commas, newlines).
 * @param {string} str
 * @returns {string}
 */
export function escapeIcsText(str = "") {
  if (!str) return "";
  return str
    .replace(/\\/g, "\\\\")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,")
    .replace(/\r?\n/g, "\\n");
}

/**
 * Format a Date object into UTC timestamp YYYYMMDDTHHMMSSZ for iCalendar DTSTAMP.
 * @param {Date} [date]
 * @returns {string}
 */
export function formatIcsUtcTimestamp(date = new Date()) {
  const pad = (n) => String(n).padStart(2, "0");
  const year = date.getUTCFullYear();
  const month = pad(date.getUTCMonth() + 1);
  const day = pad(date.getUTCDate());
  const hours = pad(date.getUTCHours());
  const minutes = pad(date.getUTCMinutes());
  const seconds = pad(date.getUTCSeconds());
  return `${year}${month}${day}T${hours}${minutes}${seconds}Z`;
}

/**
 * Parses YYYY-MM-DD or ISO string without timezone drift.
 * @param {string} dateStr
 * @returns {{ isDateOnly: boolean, dtStart: string, dtEnd: string } | null}
 */
export function formatIcsEventDates(dateStr) {
  if (!dateStr || typeof dateStr !== "string") return null;

  const trimmed = dateStr.trim();
  const dateOnlyMatch = /^(\d{4})-(\d{2})-(\d{2})$/.exec(trimmed);

  if (dateOnlyMatch) {
    const year = parseInt(dateOnlyMatch[1], 10);
    const month = parseInt(dateOnlyMatch[2], 10);
    const day = parseInt(dateOnlyMatch[3], 10);

    const pad = (n) => String(n).padStart(2, "0");
    const dtStart = `${year}${pad(month)}${pad(day)}`;

    // RFC 5545 requires VALUE=DATE DTEND for an all-day event to be the NEXT day
    const nextDate = new Date(Date.UTC(year, month - 1, day + 1));
    const dtEnd = `${nextDate.getUTCFullYear()}${pad(nextDate.getUTCMonth() + 1)}${pad(
      nextDate.getUTCDate()
    )}`;

    return { isDateOnly: true, dtStart, dtEnd };
  }

  // Handle ISO datetime strings
  const parsed = new Date(trimmed);
  if (isNaN(parsed.getTime())) return null;

  const dtStart = formatIcsUtcTimestamp(parsed);
  // Default duration of 1 hour for timed events
  const endDate = new Date(parsed.getTime() + 60 * 60 * 1000);
  const dtEnd = formatIcsUtcTimestamp(endDate);

  return { isDateOnly: false, dtStart, dtEnd };
}

/**
 * Generate RFC 5545 compliant .ics string.
 * Uses CRLF line endings per RFC 5545 specifications.
 * @param {{ title: string, description?: string, dateStr: string, noticeId?: string }} options
 * @returns {string|null}
 */
export function generateIcsContent({ title, description = "", dateStr, noticeId = "" }) {
  const dates = formatIcsEventDates(dateStr);
  if (!dates) return null;

  const cleanTitle = escapeIcsText(title || "Notice Deadline");
  const cleanDesc = escapeIcsText(
    description ? `${description} (Generated by Notice to Action)` : "Notice to Action Deadline"
  );
  const uid = `notice2action-${noticeId || "dl"}-${Date.now()}@action4ai.local`;
  const dtStamp = formatIcsUtcTimestamp();

  const startProp = dates.isDateOnly
    ? `DTSTART;VALUE=DATE:${dates.dtStart}`
    : `DTSTART:${dates.dtStart}`;
  const endProp = dates.isDateOnly
    ? `DTEND;VALUE=DATE:${dates.dtEnd}`
    : `DTEND:${dates.dtEnd}`;

  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Notice to Action//Institutional Notice Engine//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    "BEGIN:VEVENT",
    `UID:${uid}`,
    `DTSTAMP:${dtStamp}`,
    startProp,
    endProp,
    `SUMMARY:${cleanTitle}`,
    `DESCRIPTION:${cleanDesc}`,
    "STATUS:CONFIRMED",
    "TRANSP:OPAQUE",
    "END:VEVENT",
    "END:VCALENDAR",
  ];

  return lines.join("\r\n") + "\r\n";
}

/**
 * Constructs a Google Calendar template URL for direct web browser scheduling.
 * @param {{ title: string, description?: string, dateStr: string }} options
 * @returns {string|null}
 */
export function getGoogleCalendarUrl({ title, description = "", dateStr }) {
  const dates = formatIcsEventDates(dateStr);
  if (!dates) return null;

  const textParam = encodeURIComponent(title || "Notice Deadline");
  const detailsParam = encodeURIComponent(
    description ? `${description} (via Notice to Action)` : "Notice to Action Deadline"
  );

  let dateParam = "";
  if (dates.isDateOnly) {
    dateParam = `${dates.dtStart}/${dates.dtEnd}`;
  } else {
    dateParam = `${dates.dtStart}/${dates.dtEnd}`;
  }

  return `https://calendar.google.com/calendar/render?action=TEMPLATE&text=${textParam}&dates=${dateParam}&details=${detailsParam}`;
}

/**
 * Triggers an instant in-browser download of an .ics file.
 * @param {string} filename
 * @param {string} icsContent
 */
export function triggerIcsDownload(filename, icsContent) {
  if (typeof window === "undefined" || !icsContent) return;

  const blob = new Blob([icsContent], { type: "text/calendar;charset=utf-8" });
  const url = window.URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename.endsWith(".ics") ? filename : `${filename}.ics`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  window.URL.revokeObjectURL(url);
}

